-- Tablas de demostración; no borra registros existentes.
CREATE SCHEMA IF NOT EXISTS demo;
CREATE TABLE IF NOT EXISTS demo.productos (
  producto_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku TEXT NOT NULL UNIQUE,
  nombre TEXT NOT NULL,
  precio NUMERIC(12,2) NOT NULL CHECK(precio>=0),
  existencias INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS demo.empleados (
  empleado_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE,
  nombre TEXT NOT NULL,
  salario NUMERIC(12,2) NOT NULL,
  departamento TEXT
);
