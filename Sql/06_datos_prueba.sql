-- Mantener reglas existentes en instalaciones previas; evitar reiniciar preferencias.
DO $setup$
DECLARE v_id bigint;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM auditoria.tabla_auditada WHERE esquema='demo' AND nombre_tabla='productos') THEN
    v_id := auditoria.configurar_tabla('demo','productos',ARRAY['nombre','precio'],ARRAY['INSERT','UPDATE','DELETE']);
    PERFORM auditoria.desplegar_trigger(v_id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM auditoria.tabla_auditada WHERE esquema='demo' AND nombre_tabla='empleados') THEN
    v_id := auditoria.configurar_tabla('demo','empleados',ARRAY['salario','departamento'],ARRAY['INSERT','UPDATE','DELETE']);
    PERFORM auditoria.desplegar_trigger(v_id);
  END IF;
END $setup$;
