-- Medición comparativa orientativa: TRUNCATE y esquema temporal de test;
-- la medición compara operaciones sobre la MISMA tabla demo_test.rendimiento.
-- Repetir con psql -f y conservar resultados, no prometer umbral fijo.
CREATE SCHEMA IF NOT EXISTS demo_test;
DROP TABLE IF EXISTS demo_test.rendimiento;
CREATE TABLE demo_test.rendimiento(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, valor INT);
\timing on
\echo '--- 1000 INSERT sin auditoría ---'
INSERT INTO demo_test.rendimiento(valor) SELECT x FROM generate_series(1,1000)x;
TRUNCATE demo_test.rendimiento RESTART IDENTITY;
SELECT auditoria.configurar_tabla('demo_test','rendimiento',ARRAY['valor'],ARRAY['INSERT']);
SELECT auditoria.desplegar_trigger((SELECT id_tabla FROM auditoria.tabla_auditada WHERE esquema='demo_test' AND nombre_tabla='rendimiento'));
\echo '--- 1000 INSERT con auditoría ---'
INSERT INTO demo_test.rendimiento(valor) SELECT x FROM generate_series(1,1000)x;
\echo '--- Cantidad auditada ---'
SELECT count(*) AS detalles_rendimiento FROM auditoria.v_historial WHERE esquema='demo_test' AND tabla='rendimiento';
\timing off
