BEGIN;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='auditoria_admin') THEN
    CREATE ROLE auditoria_admin NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='auditoria_lector') THEN
    CREATE ROLE auditoria_lector NOLOGIN;
  END IF;
END $$;
CREATE SCHEMA IF NOT EXISTS auditoria;
REVOKE ALL ON SCHEMA auditoria FROM PUBLIC;
CREATE TABLE IF NOT EXISTS auditoria.tabla_auditada (
  id_tabla BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  esquema NAME NOT NULL,
  nombre_tabla NAME NOT NULL,
  activa BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(esquema,nombre_tabla)
);
CREATE TABLE IF NOT EXISTS auditoria.columna_auditada (
  id_columna BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_tabla BIGINT NOT NULL REFERENCES auditoria.tabla_auditada(id_tabla),
  nombre_columna NAME NOT NULL,
  UNIQUE(id_tabla,nombre_columna)
);
CREATE TABLE IF NOT EXISTS auditoria.evento (
  id_evento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(10) UNIQUE NOT NULL CHECK(nombre IN ('INSERT','UPDATE','DELETE'))
);
INSERT INTO auditoria.evento(nombre) VALUES ('INSERT'),('UPDATE'),('DELETE') ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS auditoria.configuracion_auditoria (
  id_config BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_columna BIGINT NOT NULL REFERENCES auditoria.columna_auditada(id_columna),
  id_evento INT NOT NULL REFERENCES auditoria.evento(id_evento),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_cambio TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(id_columna,id_evento)
);
CREATE TABLE IF NOT EXISTS auditoria.usuario_auditado (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_usuario TEXT NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS auditoria.estacion_trabajo (
  id_estacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip_origen VARCHAR(45) NOT NULL UNIQUE,
  nombre_host TEXT
);
CREATE TABLE IF NOT EXISTS auditoria.bitacora (
  id_bitacora BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_config BIGINT NOT NULL REFERENCES auditoria.configuracion_auditoria(id_config),
  id_usuario BIGINT NOT NULL REFERENCES auditoria.usuario_auditado(id_usuario),
  id_estacion BIGINT NOT NULL REFERENCES auditoria.estacion_trabajo(id_estacion),
  fecha_hora TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  registro_pk JSONB NOT NULL,
  valor_anterior TEXT,
  valor_nuevo TEXT,
  fila_anterior JSONB,
  fila_nueva JSONB,
  aplicacion TEXT
);
CREATE INDEX IF NOT EXISTS idx_bitacora_usuario_fecha ON auditoria.bitacora(id_usuario,fecha_hora DESC);
CREATE INDEX IF NOT EXISTS idx_bitacora_config_fecha ON auditoria.bitacora(id_config,fecha_hora DESC);
CREATE INDEX IF NOT EXISTS idx_bitacora_fecha ON auditoria.bitacora(fecha_hora DESC);
COMMIT;
